//! Device/pod rendering parity (Phase 1c, task A2).
//!
//! Every gate number this programme has taken was served with Qwen3's thinking
//! DISABLED — `gate_on_pod.py` starts `llama-server` with
//! `--chat-template-kwargs '{"enable_thinking":false}'`, which makes Qwen3's own
//! Jinja template put a PRE-CLOSED think block in the assistant prefix. The
//! phone cannot pass that kwarg: `llama_chat_apply_template` takes no Jinja
//! kwargs, so the engine appends the block itself
//! ([`ChatTemplate::finish_generation_prompt`]).
//!
//! This test asserts the two renderings are the same BYTES, against a fixture
//! generated by the real Qwen3 tokenizer (`tests/fixtures/gen_qwen3_render_parity.py`,
//! `transformers==4.57.1`, the pods' pin). It is the only assertion in the repo
//! that can make that claim: the catalog's `promptFingerprint` pins the system
//! prompt TEXT and says nothing about the template wrapped around it.

use std::path::PathBuf;

use kpack_engine::{ChatMessage, ChatTemplate, Role};

fn fixture() -> serde_json::Value {
    let path =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/qwen3-render-parity.json");
    let text =
        std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    serde_json::from_str(&text).expect("fixture is valid JSON")
}

fn s(v: &serde_json::Value) -> &str {
    v.as_str().expect("fixture field is a string")
}

/// The load-bearing assertion: for each of the three pB cases the engine's
/// ChatML rendering equals, byte for byte, what Qwen3's Jinja template produced
/// under `enable_thinking=False`.
#[test]
fn engine_rendering_matches_qwen3_jinja_byte_for_byte() {
    let doc = fixture();
    let cases = doc["cases"].as_array().expect("cases array");
    assert_eq!(cases.len(), 3, "the fixture pins three pB cases");

    for case in cases {
        let id = s(&case["id"]);
        let messages = vec![
            ChatMessage::system(s(&case["system"])),
            ChatMessage::user(s(&case["user"])),
        ];
        let rendered = ChatTemplate::ChatMl
            .render_prompt(&messages)
            .unwrap_or_else(|| panic!("{id}: ChatMl must render"));
        assert_eq!(
            rendered,
            s(&case["expected_prompt"]),
            "{id}: rendered bytes differ from Qwen3's Jinja output"
        );
        assert_eq!(
            ChatTemplate::ChatMl
                .rendered_prompt_sha256(&messages)
                .unwrap(),
            s(&case["expected_sha256"]),
            "{id}: rendered prompt sha differs"
        );
    }
}

/// From turn two onward the prompt carries assistant history. A parity proof
/// that only ever rendered a first turn would not cover the shape the device
/// actually spends most of a conversation in.
#[test]
fn multi_turn_rendering_matches_qwen3_jinja() {
    let doc = fixture();
    let case = &doc["multiTurn"];
    let messages: Vec<ChatMessage> = case["messages"]
        .as_array()
        .expect("messages array")
        .iter()
        .map(|m| ChatMessage {
            role: match s(&m["role"]) {
                "system" => Role::System,
                "user" => Role::User,
                "assistant" => Role::Assistant,
                other => panic!("unexpected fixture role {other}"),
            },
            content: s(&m["content"]).to_string(),
        })
        .collect();

    assert_eq!(
        ChatTemplate::ChatMl.render_prompt(&messages).unwrap(),
        s(&case["expected_prompt"]),
        "multi-turn rendered bytes differ from Qwen3's Jinja output"
    );
    assert_eq!(
        ChatTemplate::ChatMl
            .rendered_prompt_sha256(&messages)
            .unwrap(),
        s(&case["expected_sha256"])
    );
}

/// The pod asserts this on every rendered prompt (`train_dpo_generic.py`'s
/// `open_thinking_problem`); the device asserts it here. A template that
/// ignored `enable_thinking=False` renders a prompt that looks entirely normal
/// and lets the model open a block of its own, which is the failure the whole
/// task exists to remove.
#[test]
fn every_fixture_prompt_ends_with_the_pre_closed_block_and_opens_no_other() {
    let doc = fixture();
    let block = s(&doc["thinkBlock"]);
    assert_eq!(block, kpack_engine::QWEN3_THINK_BLOCK);

    let mut prompts: Vec<String> = doc["cases"]
        .as_array()
        .unwrap()
        .iter()
        .map(|c| s(&c["expected_prompt"]).to_string())
        .collect();
    prompts.push(s(&doc["multiTurn"]["expected_prompt"]).to_string());

    for p in prompts {
        assert!(
            p.ends_with(block),
            "prompt does not end with the block: {:?}",
            &p[p.len() - 40..]
        );
        let body = &p[..p.len() - block.len()];
        assert!(
            !body.contains("<think>"),
            "a think tag opens before the final block"
        );
        assert!(
            !body.contains("</think>"),
            "a think tag closes before the final block"
        );
    }
}

/// The catalog's `promptFingerprint` is unchanged by this task: it pins the pB
/// system prompt's text, and this task changed the template around it, not the
/// text inside it.
#[test]
fn the_catalog_prompt_fingerprint_still_pins_the_pb_system_prompt() {
    let doc = fixture();
    let fingerprint = s(&doc["promptFingerprint"]);
    assert_eq!(fingerprint, "67b7f1633f30");

    let system = s(&doc["cases"][0]["system"]);
    let sha = kpack_engine::prompt_sha256(system);
    assert_eq!(
        &sha[..12],
        fingerprint,
        "the pB system prompt no longer fingerprints to the catalog value"
    );

    let catalog = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../src-tauri/resources/catalog.triage.json");
    let text = std::fs::read_to_string(&catalog)
        .unwrap_or_else(|e| panic!("read {}: {e}", catalog.display()));
    let entries: serde_json::Value = serde_json::from_str(&text).expect("catalog is valid JSON");
    let triage = entries
        .as_array()
        .unwrap()
        .iter()
        .find(|e| e["id"] == "med-triage")
        .expect("med-triage entry");

    assert_eq!(s(&triage["promptFingerprint"]), fingerprint);
    assert_eq!(
        s(&triage["systemPrompt"]),
        system,
        "the catalog system prompt is the fixture's pB prompt"
    );
    assert_eq!(
        s(&triage["chatTemplate"]),
        "qwen",
        "the triage hero must resolve to the ChatMl family"
    );
    // Thinking no longer shares this budget with the answer, but the number
    // itself is deliberately unchanged: moving it would make the device a
    // different serve from the gate's in a second way while fixing the first.
    assert_eq!(triage["sampling"]["maxTokens"].as_u64(), Some(320));
    assert_eq!(triage["sampling"]["temperature"].as_f64(), Some(0.0));
}

// ---------------------------------------------------------------------------
// The llama.cpp half of the parity claim.
//
// The three tests above check the engine's PURE ChatML renderer against Qwen3's
// Jinja. That leaves one link unproven on host: that
// `llama_chat_apply_template`, given a real Qwen3 GGUF's embedded template,
// produces the same generation prompt the pure renderer does — i.e. that
// llama.cpp resolves Qwen3 to its built-in `chatml` format and renders the same
// bytes. It does that by string-detecting the family from the embedded template
// rather than running the Jinja, so this is a claim about llama.cpp's detection
// table and it deserves an assertion rather than a comment.
//
// It needs the `real` feature, which needs libclang + cmake to build llama.cpp.
// Point `KPACK_PARITY_GGUF` at a Qwen3 GGUF and run:
//
//     cargo test -p kpack-engine --features real --test qwen3_render_parity
//
// Without the env var it skips rather than fails: a host with the toolchain but
// no 1.2 GB model is a normal place to run the suite.
// ---------------------------------------------------------------------------
#[cfg(feature = "real")]
#[test]
fn llama_cpp_renders_the_same_bytes_as_qwen3_jinja() {
    use kpack_engine::{EngineBackend, LlamaEngine, LoadRequest, ModelSpec, SessionConfig};

    let Ok(gguf) = std::env::var("KPACK_PARITY_GGUF") else {
        eprintln!("skipping: set KPACK_PARITY_GGUF to a Qwen3 GGUF to run this");
        return;
    };

    let mut handle = LlamaEngine::new()
        .load(
            LoadRequest::new(ModelSpec::new(&gguf), Vec::new()).with_template(ChatTemplate::ChatMl),
        )
        .expect("load the base model");
    let session = handle
        .session(SessionConfig::default())
        .expect("open a session");

    let doc = fixture();
    for case in doc["cases"].as_array().unwrap() {
        let id = s(&case["id"]);
        let messages = vec![
            ChatMessage::system(s(&case["system"])),
            ChatMessage::user(s(&case["user"])),
        ];
        // The session hashes the exact bytes it would tokenise, so an equal sha
        // is an equal prompt — which is the whole assertion.
        assert_eq!(
            session.rendered_prompt_sha256(&messages).unwrap(),
            s(&case["expected_sha256"]),
            "{id}: llama.cpp's rendering differs from Qwen3's Jinja"
        );
    }
}
